package slo

import (
	"fmt"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

// Rule is a Prometheus recording or alerting rule.
type Rule struct {
	Record      string            `yaml:"record,omitempty"`
	Alert       string            `yaml:"alert,omitempty"`
	Expr        string            `yaml:"expr"`
	For         string            `yaml:"for,omitempty"`
	Labels      map[string]string `yaml:"labels,omitempty"`
	Annotations map[string]string `yaml:"annotations,omitempty"`
}

// RuleGroup is a Prometheus rule group.
type RuleGroup struct {
	Name     string `yaml:"name"`
	Interval string `yaml:"interval,omitempty"`
	Rules    []Rule `yaml:"rules"`
}

var nonWord = regexp.MustCompile(`[^a-zA-Z0-9_]`)

// RecordName is the recording-rule name for an SLI error ratio over a window.
func RecordName(window string) string {
	return "slo:sli_error:ratio_rate" + nonWord.ReplaceAllString(window, "_")
}

// GenerateRuleGroups turns the config into Prometheus rules so alerting keeps
// working even if the engine is down (Prometheus/Alertmanager own paging,
// the engine adds SLA reporting, APIs and traffic analysis).
func GenerateRuleGroups(c *Config) []RuleGroup {
	var groups []RuleGroup
	for _, s := range c.SLOs {
		bad, total, err := s.Queries()
		if err != nil {
			continue // Validate() already rejected this
		}
		labels := map[string]string{"slo": s.Name, "service": s.Service}
		rec := RuleGroup{Name: "slo-recording-" + s.Name, Interval: "30s"}
		for _, w := range c.Windows(s) {
			rec.Rules = append(rec.Rules, Rule{
				Record: RecordName(w),
				Expr:   fmt.Sprintf("(%s)\n/\n(%s)", Render(bad, w), Render(total, w)),
				Labels: labels,
			})
		}
		rec.Rules = append(rec.Rules, Rule{Record: "slo:objective:ratio", Expr: fmt.Sprintf("vector(%g)", s.Objective), Labels: labels})
		groups = append(groups, rec)

		alerts := RuleGroup{Name: "slo-alerts-" + s.Name}
		sel := fmt.Sprintf(`{slo=%q}`, s.Name)
		budget := ErrorBudget(s.Objective)
		for _, p := range c.AlertPolicies {
			th := BurnRateThreshold(p, s.Window)
			alerts.Rules = append(alerts.Rules, Rule{
				Alert: "SLOErrorBudgetBurn",
				Expr: fmt.Sprintf("(%s%s > (%g * %g))\nand\n(%s%s > (%g * %g))",
					RecordName(p.LongWindow), sel, th, budget, RecordName(p.ShortWindow), sel, th, budget),
				Labels: merge(labels, map[string]string{"severity": p.Severity, "long_window": p.LongWindow}),
				Annotations: map[string]string{
					"summary":     fmt.Sprintf("%s is burning error budget %.1fx faster than sustainable", s.Name, th),
					"description": fmt.Sprintf("Burn rate over %s and %s exceeds %.2f (objective %g over %s).", p.LongWindow, p.ShortWindow, th, s.Objective, s.Window),
				},
			})
		}
		if s.SLA != nil {
			slaBudget := ErrorBudget(s.SLA.Target)
			alerts.Rules = append(alerts.Rules,
				Rule{
					Alert:  "SLABreached",
					Expr:   fmt.Sprintf("%s%s > %g", RecordName(s.Window), sel, slaBudget),
					For:    "5m",
					Labels: merge(labels, map[string]string{"severity": "page", "contract": "sla"}),
					Annotations: map[string]string{
						"summary": fmt.Sprintf("%s violates its SLA target %g over %s", s.Name, s.SLA.Target, s.Window),
					},
				},
				Rule{
					Alert:  "SLABreachRisk",
					Expr:   fmt.Sprintf("%s%s > %g", RecordName(s.Window), sel, 0.75*slaBudget),
					For:    "15m",
					Labels: merge(labels, map[string]string{"severity": "ticket", "contract": "sla"}),
					Annotations: map[string]string{
						"summary": fmt.Sprintf("%s has consumed over 75%% of its SLA error budget", s.Name),
					},
				},
			)
		}
		groups = append(groups, alerts)
	}
	return groups
}

func merge(a, b map[string]string) map[string]string {
	out := make(map[string]string, len(a)+len(b))
	for k, v := range a {
		out[k] = v
	}
	for k, v := range b {
		out[k] = v
	}
	return out
}

// RenderRules renders either a plain Prometheus rule file ("prometheus") or a
// prometheus-operator PrometheusRule CR ("prometheusrule").
func RenderRules(c *Config, format, namespace string) ([]byte, error) {
	groups := GenerateRuleGroups(c)
	header := "# Code generated by slo-engine rules; DO NOT EDIT.\n"
	switch strings.ToLower(format) {
	case "", "prometheus":
		b, err := yaml.Marshal(map[string]any{"groups": groups})
		return append([]byte(header), b...), err
	case "prometheusrule":
		cr := map[string]any{
			"apiVersion": "monitoring.coreos.com/v1",
			"kind":       "PrometheusRule",
			"metadata": map[string]any{
				"name": "slo-rules", "namespace": namespace,
				"labels": map[string]string{"app.kubernetes.io/part-of": "otel-slo-traffic-monitor"},
			},
			"spec": map[string]any{"groups": groups},
		}
		b, err := yaml.Marshal(cr)
		return append([]byte(header), b...), err
	default:
		return nil, fmt.Errorf("unknown rules format %q", format)
	}
}
